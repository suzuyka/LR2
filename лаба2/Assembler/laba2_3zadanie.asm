section .bss
    input  resb 32        ; Буфер для ввода строки (до 32 байт)
    output resb 1         ; Буфер для вывода одного символа (результата)

section .data
    space   db ' '        ; Символ пробела (не используется в этом варианте)
    newline db 10         ; Символ новой строки (LF)

section .text
    global _start         ; Точка входа программы

_start:
    ; --- Чтение количества чисел ---
    mov rax, 0            ; sys_read (номер системного вызова)
    mov rdi, 0            ; stdin (дескриптор 0)
    mov rsi, input        ; адрес буфера для чтения
    mov rdx, 32           ; максимальное количество байт для чтения
    syscall               ; вызов ядра: читать из stdin

    call atoi             ; преобразовать введённую строку в число (количество чисел)
    mov r12, rax          ; сохранить количество чисел в r12

.read_loop:
    test r12, r12         ; проверить, не равно ли количество чисел 0
    jz .exit              ; если 0, перейти к завершению программы

    ; --- Чтение очередного числа ---
    mov rax, 0            ; sys_read
    mov rdi, 0            ; stdin
    mov rsi, input        ; буфер для чтения
    mov rdx, 32           ; максимум 32 байта
    syscall               ; читать строку с числом

    xor rcx, rcx          ; rcx = счётчик нечётных цифр, обнуляем
    xor rdx, rdx          ; rdx = индекс символа в буфере, обнуляем

.count_loop:
    mov al, [input + rdx] ; загружаем символ из буфера по индексу rdx
    cmp al, 10            ; сравниваем с символом новой строки '\n'
    je .print_result      ; если встретили '\n', заканчиваем подсчёт

    cmp al, '0'           ; проверяем, что символ >= '0'
    jb .skip_inc          ; если меньше '0', пропускаем символ

    cmp al, '9'           ; проверяем, что символ <= '9'
    ja .skip_inc          ; если больше '9', пропускаем символ

    sub al, '0'           ; преобразуем ASCII-цифру в число 0-9
    test al, 1            ; проверяем младший бит (1 - нечётное число)
    jz .skip_inc          ; если бит 0 (чётное), пропускаем

    inc rcx               ; увеличиваем счётчик нечётных цифр

.skip_inc:
    inc rdx               ; переходим к следующему символу
    jmp .count_loop       ; повторяем цикл

.print_result:
    mov rax, rcx          ; копируем счётчик нечётных цифр в rax
    add al, '0'           ; преобразуем в ASCII-символ
    mov [output], al      ; сохраняем символ в буфер

    ; --- Вывод результата ---
    mov rax, 1            ; sys_write (номер вызова)
    mov rdi, 1            ; stdout (дескриптор 1)
    mov rsi, output       ; адрес буфера с символом
    mov rdx, 1            ; длина вывода 1 байт
    syscall               ; выводим символ

    ; --- Вывод новой строки ---
    mov rax, 1            ; sys_write
    mov rdi, 1            ; stdout
    mov rsi, newline      ; адрес символа новой строки
    mov rdx, 1            ; длина 1 байт
    syscall               ; выводим новую строку

    dec r12               ; уменьшаем количество оставшихся чисел
    jmp .read_loop        ; читаем следующее число

.exit:
    ; --- Вывод новой строки (после всех чисел) ---
    mov rax, 1            ; sys_write
    mov rdi, 1            ; stdout
    mov rsi, newline      ; адрес символа новой строки
    mov rdx, 1            ; длина 1 байт
    syscall               ; выводим перевод строки

    ; --- Завершение программы ---
    mov rax, 60           ; sys_exit (номер вызова)
    xor rdi, rdi          ; код возврата 0
    syscall               ; выход из программы

; --- Функция atoi ---
; Преобразует строку из input в число, возвращает в rax
atoi:
    xor rax, rax          ; обнуляем rax (результат)
    xor rcx, rcx          ; обнуляем индекс

.convert_loop:
    movzx rdx, byte [input + rcx] ; загружаем символ
    cmp rdx, 10           ; проверяем на '\n'
    je .done              ; если новая строка - конец

    cmp rdx, '0'          ; проверяем, что символ >= '0'
    jb .done              ; если меньше - конец

    cmp rdx, '9'          ; проверяем, что символ <= '9'
    ja .done              ; если больше - конец

    sub rdx, '0'          ; переводим ASCII в число
    imul rax, 10          ; умножаем результат на 10
    add rax, rdx          ; добавляем новую цифру
    inc rcx               ; переходим к следующему символу
    jmp .convert_loop

.done:
    ret                   ; возвращаемся, результат в rax

