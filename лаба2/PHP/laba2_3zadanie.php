<?php
function count_dig($num) {
    // Подсчёт количества нечётных цифр в числе
    $count = 0;
    while ($num > 0) {
        $dig = $num % 10;           // Получаем последнюю цифру
        if ($dig % 2 != 0) {        // Проверяем, нечётная ли цифра
            $count++;
        }
        $num = (int) ($num / 10);   // Убираем последнюю цифру
    }
    return $count;
}

echo "Введите количество чисел: ";
$num = (int) fgets(STDIN);  // Считываем количество чисел

for ($i = 0; $i < $num; $i++) {
    echo "Введите число: ";
    $n = (int) fgets(STDIN);  // Считываем число
    echo count_dig($n);       // Выводим количество нечётных цифр
    echo "\n";
}
?>
