import java.util.Scanner

fun main() {
    val reader = Scanner(System.`in`)

    print("Введите N и M: ")
    var N = reader.nextInt()  // начальное количество полных банок
    val M = reader.nextInt()  // количество пустых банок, необходимое для обмена

    var total = 0     // общее количество выпитых банок
    var empty = 0     // количество пустых банок
    var iterations = 0  // количество итераций (шагов процесса)

    println("\nДано:")
    for (j in 0 until N) print("☺")  // выводим символы для полных банок
    println()

    println("\nПроцесс:")

    // Пока есть полные банки или достаточно пустых для обмена
    while (N > 0 || empty >= M) {
        total += N       // добавляем выпитые банки к общему счёту
        empty += N       // пустые банки увеличиваются на количество выпитых
        N = 0            // все полные банки выпиты

        iterations++     // увеличиваем счётчик итераций

        for (i in 0 until empty) print("©")  // выводим пустые банки
        println(" (пустые банки)")

        // Если достаточно пустых банок для обмена
        if (empty >= M) {
            N = empty / M       // получаем новые полные банки после обмена
            empty %= M          // остаток пустых банок после обмена

            iterations++        // увеличиваем счётчик итераций

            for (i in 0 until N) print("☺")  // выводим новые полные банки
            println(" (полные банки после обмена)")
        }
    }

    println("\nВыпитые банки: $total")
    println("Итерации: $iterations")
}

